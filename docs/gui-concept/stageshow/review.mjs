import { chromium } from 'playwright-core'
import { mkdirSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import { resolve } from 'node:path'
const browser = await chromium.launch({ channel: 'msedge' })
mkdirSync('captures', { recursive: true })
const errors = []
const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' })
page.on('pageerror', e => errors.push(e.message))
await page.route('http**', route => route.abort())
await page.goto(pathToFileURL(resolve('../workbench-preview.html')).href)
await page.locator('.master-photo').waitFor()
await page.waitForFunction(() => [...document.images].every(i => i.complete && i.naturalWidth > 0))
await page.locator('.revelare-study').screenshot({ path: '../workbench-light.png' })
const require = (test, message) => { if (!test) throw new Error(message) }
await page.getByRole('button', { name: '切换深色', exact: true }).click()
await page.locator('.revelare-study').screenshot({ path: '../workbench-dark.png' })
require(await page.locator('.ss-stage').getAttribute('data-theme') === 'dark', 'Theme failed')
await page.getByTitle('查看负片（N）', { exact: true }).focus()
await page.keyboard.press('n')
require(await page.getByTitle('查看负片（N）', { exact: true }).getAttribute('aria-pressed') === 'true', 'N failed')
await page.keyboard.press('n')
await page.keyboard.press('k')
require(await page.getByTitle('前后对比（K）', { exact: true }).getAttribute('aria-pressed') === 'true', 'K failed')
await page.keyboard.press('k')
await page.keyboard.press('?')
require(await page.locator('.shortcut-shelf').count() === 1, 'Shortcut hints failed')
await page.keyboard.press('Escape')
require(await page.locator('.shortcut-shelf').count() === 0, 'Escape failed')
const density = page.getByRole('spinbutton', { name: 'D_min 数值', exact: true })
await density.fill('0.615')
require(await density.inputValue() === '0.615', 'Numeric edit failed')
await page.getByRole('button', { name: '片基采样', exact: true }).click()
require(await page.locator('.sampling-prompt').getAttribute('data-visible') === 'true', 'Sampling activation failed')
await page.locator('.master-photo').click()
require(await density.inputValue() === '0.426', 'Sample response failed')
await page.getByRole('button', { name: /同步标定到整卷/ }).click()
require(await page.getByRole('button', { name: /已同步到整卷/ }).count() === 1, 'Sync feedback failed')
await page.getByRole('tab', { name: '成片调整', exact: true }).click()
await page.getByRole('spinbutton', { name: '曝光 数值', exact: true }).fill('1.000')
require((await page.locator('.master-photo').getAttribute('style')).includes('brightness(2)'), 'Exposure preview failed')
await page.getByRole('button', { name: '导出', exact: true }).click()
require(await page.locator('#export-info').evaluate(el => el.matches(':popover-open')), 'Export entry failed')
await page.keyboard.press('Escape')
await page.getByRole('tab', { name: '底片校准', exact: true }).click()
for (const width of [1024, 740, 390]) {
  await page.setViewportSize({ width, height: 900 })
  await page.locator('.revelare-study').screenshot({ path: `captures/width-${width}.png` })
  const overflow = await page.evaluate(() => [...document.querySelectorAll('.instrument input')].filter(el => {
    if (el.getClientRects().length === 0) return false
    const r = el.getBoundingClientRect(), p = el.parentElement.getBoundingClientRect()
    return r.right > p.right + 1 || r.left < p.left - 1
  }).length)
  require(overflow === 0, `Numeric layout overflow at ${width}`)
}
await page.emulateMedia({ reducedMotion: 'no-preference' })
await page.setViewportSize({ width: 1280, height: 900 })
await page.getByRole('button', { name: '演示采样', exact: true }).click()
await page.waitForFunction(() => document.querySelector('.sampling-prompt')?.getAttribute('data-visible') === 'true')
await page.locator('.revelare-study').screenshot({ path: 'captures/sampling-active.png' })
await page.waitForFunction(() => document.querySelector('.comparison')?.getAttribute('data-visible') === 'true', { timeout: 15000 })
await page.locator('.revelare-study').screenshot({ path: 'captures/comparison-active.png' })
await page.waitForFunction(() => document.querySelector('.comparison')?.getAttribute('data-visible') === 'false')
require(errors.length === 0, errors.join('\n'))
console.log('Standalone offline assets, light/dark, N/K/?/Escape, numeric editing, sampling, sync, exposure, export popover, 1280/1024/740/390 layouts and authored animation: passed.')
await browser.close()
